// Refresh only app-owned instructions in cached system context; never rewrite the records themselves.
function upgradeLegacySharedContext(content) {
    if (typeof content !== 'string') return content;
    if (!content.startsWith('Context:\n') && !content.startsWith('Context:\r\n')) return content;
    return content
        .replace(/\[时间行为约束\]\r?\n(?:- [^\r\n]*\r?\n)+/, () => TIME_CONTEXT_GUIDANCE)
        .replace('[===== CITY SOURCE: 商业街（真实生活）实时世界线 =====]', '[===== CITY SOURCE: 商业街生活背景与历史记录 =====]')
        .replace(/\[商业街规则\]\r?\n[\s\S]*?(?=\[可用商业街地点信号\]|\r?\n【(?:公告区|本人亲历记录|公共事件))/, () => CITY_REFERENCE_GUIDANCE)
        .replace(/\[商业街问答优先级\]\r?\n(?:- [^\r\n]*\r?\n)+/, '')
        .replace(/\[商业街执行规则\]\r?\n(?:- [^\r\n]*\r?\n)+/, '')
        .replace(/\[GROUP SOURCE RULES\]\r?\n[\s\S]*?(?=群聊《)/, () => GROUP_REFERENCE_GUIDANCE)
        .replace('只把下面这些说成“我做过/我刚经历过”。', '下面是本人过去的活动记录；其中引用的旧对白只作历史参考。')
        .replace('当前没有可直接引用的本人商业街行动记录。', '本次未提供本人商业街行动记录。')
        .replace('[嫉妒状态]: 强烈嫉妒已激活；语气可更尖锐、委屈、试探、索要独占关注。', '[嫉妒状态]: 当前记录为强烈嫉妒；这是角色自身感受，不是用户动机的证据。')
        .replace(/(\[商业街未回\]: 连续 \d+ 次主动联系未获回应)；下次语气应更黏人、急切、委屈或带刺。/, '$1；原因未记录。')
        .replace('[商业街未回]: 最近主动联系过用户但还没等到回音，会更在意对方把注意力给了谁。', '[商业街未回]: 最近主动联系过用户，目前尚无后续回复；原因未记录。')
        .replace(/\[商业街余震\]: 用户是在你连续 (\d+) 次被晾后才回复；这次不能立刻恢复平静，仍要带出被冷落后的余震。/, '[商业街联系进展]: 连续 $1 次主动联系后收到了用户回复。')
        .replace('[忙碌余压]: 这条私聊是在工作被打断的情况下回出去的。你心里清楚，聊得越久，手上的活越容易被拖慢，烦躁和紧张感也会往上拱。', '[当前活动]: 工作中。')
        .replace('[补觉余压]: 这条私聊是在休息被打断的情况下回出去的。你还没完全清醒，越聊越会觉得这次补觉被搅散了，醒来后只会更累。', '[当前活动]: 休息中。');
}

